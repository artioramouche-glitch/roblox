#!/usr/bin/env node
/**
 * Generates docs/GAMEKIT.md (English reference for AIs and humans) from the catalog,
 * so the documentation can never drift from the code. Run after `npm run build`.
 */
import { writeFileSync } from 'fs';

const dist = new URL('../dist/gamekit/', import.meta.url);
const { GUIDES, catalogText, systemDoc, templateDoc } = await import(new URL('knowledge.js', dist));
const { SYSTEMS } = await import(new URL('catalog.js', dist));
const { TEMPLATES } = await import(new URL('templates.js', dist));
const { GAMEKIT_TOOLS } = await import(new URL('tools.js', dist));

const parts = [
  '# GameKit reference',
  '',
  '> Generated by `node scripts/gen-gamekit-docs.mjs` from the source code. Do not edit by hand.',
  '> The same content is served by the MCP server (`roblox_guide`, `gamekit://` resources).',
  '',
  '## GameKit tools',
  '',
  ...GAMEKIT_TOOLS.map((t) => `- **${t.name}** — ${t.description}`),
  '',
  catalogText().replace(/^# GameKit catalog\n/, ''),
  '',
  '## Templates in detail',
  ...TEMPLATES.map((t) => templateDoc(t.id).replace(/^# /, '### ')),
  '',
  '## Systems in detail',
  ...SYSTEMS.map((s) => systemDoc(s.id).replace(/^# /, '### ').replace(/\n## /g, '\n#### ')),
  '',
  '## Guides',
  ...Object.entries(GUIDES).map(([k, g]) => `### ${g.title} (\`${k}\`)\n${g.body.replace(/\n## /g, '\n#### ')}`),
];
writeFileSync(new URL('../docs/GAMEKIT.md', import.meta.url), parts.join('\n') + '\n');
console.log('docs/GAMEKIT.md written');
