#!/usr/bin/env node
/**
 * Embeds every gamekit/**\/*.luau file into packages/core/src/gamekit/generated/luau-sources.ts so the
 * MCP server ships the Luau library inside its build (no runtime file lookups).
 * Run automatically by `npm run build`; `--check` exits 1 when the file is stale.
 */
import { readdirSync, readFileSync, statSync, writeFileSync, mkdirSync, existsSync } from 'fs';
import { join, relative, dirname } from 'path';
import { fileURLToPath } from 'url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const libDir = join(root, 'gamekit');
const outFile = join(root, 'packages', 'core', 'src', 'gamekit', 'generated', 'luau-sources.ts');

function walk(dir) {
  const out = [];
  for (const name of readdirSync(dir).sort()) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) out.push(...walk(full));
    else if (name.endsWith('.luau')) out.push(full);
  }
  return out;
}

const entries = walk(libDir).map((file) => {
  const key = relative(libDir, file).split('\\').join('/');
  const source = readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
  return `  ${JSON.stringify(key)}: ${JSON.stringify(source)},`;
});

const content = `// AUTO-GENERATED by scripts/embed-gamekit.mjs from the gamekit/ folder. Do not edit.
// Edit the .luau files in gamekit/ and run \`npm run build\` (or \`node scripts/embed-gamekit.mjs\`).

export const LUAU_SOURCES: Record<string, string> = {
${entries.join('\n')}
};
`;

if (process.argv.includes('--check')) {
  const current = existsSync(outFile) ? readFileSync(outFile, 'utf8') : '';
  if (current !== content) {
    console.error('packages/core/src/gamekit/generated/luau-sources.ts is out of date. Run: node scripts/embed-gamekit.mjs');
    process.exit(1);
  }
  console.log('[embed-gamekit] up to date');
} else {
  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(outFile, content);
  console.log(`[embed-gamekit] ${entries.length} Luau files -> ${relative(root, outFile)}`);
}
