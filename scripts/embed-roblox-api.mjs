#!/usr/bin/env node
/**
 * Builds a compact index of the Roblox API (classes and their members, services, creatable
 * classes, enums, datatype constructors, deprecated members) from the luau-lsp type
 * definitions in packages/core/assets/globalTypes.d.luau, into
 * packages/core/src/gamekit/generated/roblox-api.ts. check_luau / write_script use it to catch
 * invented APIs ("GetService('Player')", "Enum.Material.Wooden", "part:SetColor()").
 * Run by `npm run build`; `--check` exits 1 when the file is stale.
 */
import { existsSync, readFileSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const defsFile = join(root, 'packages', 'core', 'assets', 'globalTypes.d.luau');
const outFile = join(root, 'packages', 'core', 'src', 'gamekit', 'generated', 'roblox-api.ts');

const lines = readFileSync(defsFile, 'utf8').replace(/\r\n/g, '\n').split('\n');
const meta = JSON.parse(lines[0].replace(/^--#METADATA#/, ''));

const classes = {}; // name -> { s: super, m: Set, d: Map(member -> replacement) }
const enums = {};
const globals = {};

for (let i = 1; i < lines.length; i++) {
  const line = lines[i];
  let m = /^declare extern type (\w+)(?: extends (\w+))? with( end)?$/.exec(line);
  if (m) {
    const [, name, parent, closed] = m;
    const enumMatch = /^Enum(\w+)_INTERNAL$/.exec(name);
    const items = [];
    const cls = { s: parent ?? '', m: new Set(), d: new Map() };
    let deprecated = null;
    if (!closed) {
      for (i++; i < lines.length && lines[i] !== 'end'; i++) {
        const member = lines[i];
        const dep = /^\t@\[deprecated \{use = "([^"]+)"\}\]/.exec(member);
        if (dep) { deprecated = dep[1].replace(/^\w+[:.]/, ''); continue; }
        if (/^\t@deprecated/.test(member)) { deprecated = ''; continue; }
        const fn = /^\t+function (\w+)\(/.exec(member);
        const prop = /^\t+(\w+):/.exec(member);
        const memberName = fn?.[1] ?? prop?.[1];
        if (!memberName) continue;
        if (enumMatch) items.push(memberName);
        else if (deprecated !== null) cls.d.set(memberName, deprecated);
        else cls.m.add(memberName);
        deprecated = null;
      }
    }
    if (enumMatch) enums[enumMatch[1]] = items;
    else if (!/^Enum\w+$/.test(name)) classes[name] = cls;
    continue;
  }
  m = /^declare (\w+): \{$/.exec(line);
  if (m) {
    const fields = [];
    for (i++; i < lines.length && lines[i] !== '}'; i++) {
      const field = /^\s+(\w+):/.exec(lines[i]);
      if (field) fields.push(field[1]);
    }
    globals[m[1]] = fields;
  }
}

// Datatypes whose static members we check (Vector3.new, CFrame.lookAt, Color3.fromRGB...).
const DATATYPES = ['Vector3', 'Vector2', 'CFrame', 'Color3', 'UDim', 'UDim2', 'BrickColor', 'TweenInfo', 'NumberRange',
  'NumberSequence', 'ColorSequence', 'NumberSequenceKeypoint', 'ColorSequenceKeypoint', 'Ray', 'Region3', 'Rect',
  'RaycastParams', 'OverlapParams', 'Random', 'DateTime', 'Instance', 'PhysicalProperties', 'Font', 'Faces', 'Axes',
  'Vector3int16', 'Vector2int16', 'Region3int16', 'task', 'Content', 'SharedTable', 'buffer'];

const pack = (list) => [...list].sort().join(',');
const classEntries = Object.entries(classes)
  .filter(([name]) => !/^(Enum|ENUM_LIST)/.test(name))
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([name, c]) => {
    const deps = [...c.d.entries()].map(([k, v]) => (v ? `${k}>${v}` : k)).sort().join(',');
    return `  ${name}: [${JSON.stringify(c.s)}, ${JSON.stringify(pack(c.m))}${deps ? `, ${JSON.stringify(deps)}` : ''}],`;
  });
const enumEntries = Object.entries(enums).sort(([a], [b]) => a.localeCompare(b)).map(([name, items]) => `  ${name}: ${JSON.stringify(pack(items))},`);
const globalEntries = DATATYPES.filter((d) => globals[d]).map((d) => `  ${d}: ${JSON.stringify(pack(globals[d]))},`);

const content = `// AUTO-GENERATED by scripts/embed-roblox-api.mjs from packages/core/assets/globalTypes.d.luau. Do not edit.
/* eslint-disable */

/** class -> [superclass, members (comma list), deprecated members ("old>New" comma list)] */
export const API_CLASSES: Record<string, [string, string, string?]> = {
${classEntries.join('\n')}
};

/** Enum type -> items (comma list). */
export const API_ENUMS: Record<string, string> = {
${enumEntries.join('\n')}
};

/** Datatype globals -> static members (comma list). */
export const API_GLOBALS: Record<string, string> = {
${globalEntries.join('\n')}
};

export const API_SERVICES = ${JSON.stringify(pack(meta.SERVICES))};
export const API_CREATABLE = ${JSON.stringify(pack(meta.CREATABLE_INSTANCES))};
`;

if (process.argv.includes('--check')) {
  const current = existsSync(outFile) ? readFileSync(outFile, 'utf8') : '';
  if (current !== content) {
    console.error('[embed-roblox-api] generated/roblox-api.ts is stale: run node scripts/embed-roblox-api.mjs');
    process.exit(1);
  }
  console.log('[embed-roblox-api] up to date');
} else {
  writeFileSync(outFile, content);
  console.log(`[embed-roblox-api] ${classEntries.length} classes, ${enumEntries.length} enums, ${globalEntries.length} datatypes -> ${outFile.slice(root.length + 1)} (${Math.round(content.length / 1024)} KB)`);
}
